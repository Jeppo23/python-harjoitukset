ensimmäinen = float (input("Ilmoita ensimmäinen kokonaisluku")) 
toinen = float (input("Ilmoita toinen kokonaisluku")) 
kolmas = float (input("Ilmoita kolmas kokonaisluku")) 
summa = ensimmäinen + toinen + kolmas 
tulo = ensimmäinen * toinen * kolmas
keskiarvo = ensimmäinen + toinen + kolmas / 3
print("summa:", summa )
print("tulo:", tulo )
print("keskiarvo:", keskiarvo)